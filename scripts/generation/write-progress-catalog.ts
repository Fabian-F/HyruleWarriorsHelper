import { mkdirSync, writeFileSync } from 'node:fs';
import { format, resolveConfig } from 'prettier';
import { legendMissions } from '../../src/data/legend/missions';
import { mapMetadata } from '../../src/data/maps/map-metadata';
import { loadMap } from '../../src/domain/maps/map-loader';
import { buildProgressCatalog } from '../../src/data/progress/build-catalog';

async function main(): Promise<void> {
  const maps = await Promise.all(mapMetadata.map((map) => loadMap(map.id)));
  const catalog = buildProgressCatalog(maps, legendMissions);
  const outputPath = 'src/data/progress/catalog.ts';
  // Bound TypeScript's inference cost for the large heterogeneous metadata array.
  const sections: string[] = [];
  const names: string[] = [];
  for (let start = 0; start < catalog.entries.length; start += 100) {
    const name = `entries${names.length}`;
    names.push(name);
    sections.push(
      `const ${name}: readonly ProgressEntry[] = ${JSON.stringify(catalog.entries.slice(start, start + 100))};`,
    );
  }
  mkdirSync('src/data/progress', { recursive: true });
  writeFileSync(
    outputPath,
    await format(
      `// Generated by npm run generate:progress-catalog. Do not edit manually.
import type { ProgressCatalog, ProgressEntry } from '../../domain/progress/progress-catalog';
${sections.join('\n\n')}
export const progressCatalog: ProgressCatalog = {
  entries: [${names.map((name) => `...${name}`).join(', ')}],
  aRankRelations: ${JSON.stringify(catalog.aRankRelations)},
};
`,
      { ...(await resolveConfig(outputPath)), parser: 'typescript' },
    ),
  );
  const counts = Object.fromEntries(
    [...new Set(catalog.entries.map((entry) => entry.category))].map((category) => [
      category,
      catalog.entries.filter((entry) => entry.category === category).length,
    ]),
  );
  console.log(
    `Wrote ${catalog.entries.length} progress entries and ${catalog.aRankRelations.length} A-rank relations.`,
    counts,
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
