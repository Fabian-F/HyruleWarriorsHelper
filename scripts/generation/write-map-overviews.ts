import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { format, resolveConfig } from 'prettier';
import { mapMetadata } from '../../src/data/maps/map-metadata';
import { loadMap } from '../../src/domain/maps/map-loader';
import {
  getMapStatistics,
  getMapCharacterUnlocks,
  type MapOverview,
} from '../../src/domain/maps/map-overview';
import { getMapSize } from '../../src/domain/maps/map.model';
import { getTileCoordinates } from '../../src/domain/maps/tile-coordinates';

async function main(): Promise<void> {
  const overviews: MapOverview[] = [];
  for (const metadata of mapMetadata) {
    const map = await loadMap(metadata.id);
    const size = getMapSize(map);
    // Match the viewer's grid, including empty positions on sparse maps.
    const tileIds = [...map.tiles.map((tile) => tile.id), ...(map.decorativeTiles ?? [])];
    const availableIds = tileIds.filter((id) =>
      existsSync(`public/map-tiles/${map.id}/${id}.webp`),
    );
    const missingMissions = map.tiles.filter(
      (tile) => !existsSync(`public/map-tiles/${map.id}/${tile.id}.webp`),
    );
    // Rewards Map assets are still being added; missing fields remain transparent.
    if (missingMissions.length && map.id !== 'rewards') {
      throw new Error(
        `Missing tile images: ${map.id}/${missingMissions.map((tile) => tile.id).join(', ')}`,
      );
    }
    const layout = {
      id: map.id,
      ...size,
      tiles: availableIds.map((id) => ({ id, ...getTileCoordinates(id) })),
    };
    const preview = availableIds.length
      ? (JSON.parse(
          execFileSync('python3', ['scripts/generation/write-map-preview.py'], {
            input: JSON.stringify(layout),
            encoding: 'utf8',
          }),
        ) as MapOverview['preview'])
      : null;
    const statistics = getMapStatistics(map);
    if (statistics.tiles !== metadata.tileCount) throw new Error(`Tile count mismatch: ${map.id}`);
    overviews.push({
      id: map.id,
      statistics,
      characterUnlocks: getMapCharacterUnlocks(map),
      preview,
    });
    console.log(`${map.id}: ${JSON.stringify(statistics)}`);
  }
  const output = 'src/data/maps/map-overviews.ts';
  mkdirSync('src/data/maps', { recursive: true });
  writeFileSync(
    output,
    await format(
      `// Generated by npm run generate:map-overviews. Do not edit manually.
import type { MapOverview } from '../../domain/maps/map-overview';
export const mapOverviews = ${JSON.stringify(overviews)} as const satisfies readonly MapOverview[];
`,
      { ...(await resolveConfig(output)), parser: 'typescript' },
    ),
  );
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
